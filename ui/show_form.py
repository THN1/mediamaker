"""Shows a generated form for viewing (without logic) or saves a picture of it.

Usage:  python3 show_form.py frmRemoveLogo [--dir FOLDER] [--shot image.png]
FOLDER contains the files generated by frm2qt.py (default: generated). With --shot the window is built once
on the screen and saved as a PNG; this way the view can be compared with the VB6 IDE.
The window always appears light (Fusion style); with --system-theme the desktop's theme is used instead.
With --offscreen this happens without a visible window; but then other fonts apply and the message
"This plugin does not support propagateSizeHints()" appears (harmless).
"""
import importlib
import os
import sys

if "--offscreen" in sys.argv:
    os.environ["QT_QPA_PLATFORM"] = "offscreen"

from PySide6 import QtCore, QtWidgets


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--") and sys.argv[sys.argv.index(a) - 1] not in ("--dir", "--shot")]
    if not args:
        sys.exit(__doc__)
    name = args[0]
    folder = sys.argv[sys.argv.index("--dir") + 1] if "--dir" in sys.argv else os.path.join(os.path.dirname(os.path.abspath(__file__)), "generated")
    sys.path.insert(0, os.path.abspath(folder))
    sys.path.insert(1, os.path.dirname(os.path.abspath(__file__)))      # vbqt.py
    app = QtWidgets.QApplication(sys.argv)
    import vbqt
    if "--system-theme" not in sys.argv:
        vbqt.apply_light_theme(app)
    module = importlib.import_module(f"ui_{name}")
    window = getattr(module, f"{name}Base")()
    window.show()
    if "--shot" in sys.argv:
        out = sys.argv[sys.argv.index("--shot") + 1]
        app.processEvents()
        window.grab().save(out)
        print("saved:", out)
        return
    sys.exit(app.exec())


if __name__ == "__main__":
    main()
