"""Makes languages.py (the table of ISO 639-2 language codes) from the table of the package iso-codes:

    python3 tools/make_languages.py [/usr/share/xml/iso-codes/iso_639-2.xml] > languages.py

Only needed when the table is to be made again; the program does not read the XML file."""
import sys
import xml.etree.ElementTree as ET

path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/xml/iso-codes/iso_639-2.xml"
rows = []
for e in ET.parse(path).getroot().iter("iso_639_entry"):
    t, b, one, name = e.get("iso_639_2T_code"), e.get("iso_639_2B_code"), e.get("iso_639_1_code") or "", e.get("name")
    rows.append((t, b, one, name.split(";")[0].strip()))
rows.sort()
print('"""ISO 639-2 language codes (three letters) for the language of audio and subtitle tracks (multitrack dialog).\n')
print("Generated by tools/make_languages.py from the table of the package iso-codes (data of the Library of Congress, ISO 639-2). Do not edit by hand.")
print('Each language has a terminologic code (T, e.g. deu) and sometimes a bibliographic one (B, e.g. ger): ffmpeg takes both, MP4 and the tracks of most files use T.\n"""')
print("\nNAMES = {  # T code -> English name")
for t, b, one, name in rows:
    print(f"    {t!r}: {name!r},")
print("}\n\nB_TO_T = {  # bibliographic code -> terminologic code (only where they differ)")
for t, b, one, name in rows:
    if b != t:
        print(f"    {b!r}: {t!r},")
print("}\n\nONE_TO_T = {  # two letter code (ISO 639-1) -> terminologic code")
for t, b, one, name in rows:
    if one:
        print(f"    {one!r}: {t!r},")
print("}")
