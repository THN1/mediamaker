def quick_probe(path: str) -> MediaInfo:
    """Quick analysis: reads only the start and end of the file (important on network drives). The number of frames is
        estimated from duration and frame rate and counted exactly later in the background."""
    return full_probe(path, exact_frames=False)


def existing_dirs(dirs, timeout: float = 1.0) -> list:
    """The folders of the list that exist. A folder on a network drive that does not answer must not keep the file dialog from opening: what has not answered after `timeout` seconds
    (all together) is left out."""
    dirs = list(dirs)
    if not dirs:
        return []
    from concurrent.futures import ThreadPoolExecutor
    pool = ThreadPoolExecutor(max_workers=len(dirs))
    futures = [pool.submit(os.path.isdir, d) for d in dirs]
    deadline = time.monotonic() + timeout
    found = []
    for d, future in zip(dirs, futures):
        try:
            if future.result(timeout=max(0.0, deadline - time.monotonic())):
                found.append(d)
        except Exception:
            pass
    pool.shutdown(wait=False)
    return found


class FrameCounter(QtCore.QThread):
    """Counts the frames of a file in the background (reads the whole file once)."""

    counted = QtCore.Signal(str, int, int, float)          # path, frames, discarded packets, PTS of the first keyframe
    ended = QtCore.Signal(object)                           # always, when the thread ends: with a result, cancelled or with an error
    progress = QtCore.Signal(str, float)                    # path, the time in seconds of the packet read last (now and then: how far the counting has got)

    def __init__(self, path: str, count_fn):
        super().__init__()
        self.path, self.count_fn = path, count_fn
        self._proc = None
        self.cancelled = False
        self.done = False                                   # set by the main window when it has been told that the counting ended

    def _remember(self, proc) -> None:
        self._proc = proc
        if self.cancelled:
            proc.terminate()

    def cancel(self) -> None:
        self.cancelled = True
        if self._proc is not None and self._proc.poll() is None:
            self._proc.terminate()

    def run(self) -> None:
        try:
            try:
                kwargs = {"on_start": self._remember}
                if "on_progress" in inspect.signature(self.count_fn).parameters:
                    kwargs["on_progress"] = lambda seconds: self.progress.emit(self.path, seconds)
                frames, dropped, key_pts = self.count_fn(self.path, **kwargs)
            except Exception:                               # cancelled, file not readable or any other error: the estimate stays
                return
            if not self.cancelled:
                self.counted.emit(self.path, frames, dropped, key_pts)
        finally:
            self.ended.emit(self)                           # (the note in the title must go in every case; before, only a result removed it)


