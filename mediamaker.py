    def duplicate_segment(self) -> None:
        """New segment behind the current one: starts at the end of the current one and takes over crop and logo. Then it jumps ahead by
                the minimum length of a commercial (option pause) and looks for the start of the movie."""
        seg = self.segment
        if seg.end >= seg.total_frames:
            # Not cut at the end: nothing to search for. The segment is simply added again in full length.
            new = dataclasses.replace(seg, index=len(self.segments) + 1, start=seg.first_frame, end=seg.total_frames)
            self.segments.insert(self.current + 1, new)
            self.current += 1
            self.refresh_list()
            self._save()
            self.lblText_Upd()
            self.lvwSegments.select_row(self.current)
            self.lvwSegments_Click()
            return
        new = dataclasses.replace(seg, index=len(self.segments) + 1, start=seg.end, end=seg.total_frames)
        self.segments.append(new)
        self.current = len(self.segments) - 1
        self.refresh_list()
        self._save()
        self.lblText_Upd()
        self._preview_held = True                                    # the new segment is NOT played in VLC now (that was heard and seen during the search), but at the end of it
        self.lvwSegments.select_row(self.current)
        self.lvwSegments_Click()                                     # load the preview (the timeline shows marker A); VLC shows nothing yet
        pause = int(self.options.get("pause", 160))
        target = min(new.total_frames, new.start + round(pause * float(new.fps)))
        self._go(target)
        self.show_frame(target)
        # In VB6 the search only ran if all segments came from the same file. Here it always runs: if segments of other files
        # are still in the list (e.g. from earlier tests), that should not prevent the new
        # segment from finding its movie start.
        debug_log(f"duplicate: searching for the start of the movie from frame {self.shown(target)} (several sources: {self.multiple()})")
        debug_log(lambda: f"duplicate: the preview is held, starting the search ({self.player.describe()})")
        self.mnuEnd_Click()
        if not self._seek_running():
            self.release_preview(True)                               # no search was started (it said why): show the picture at the target now

