    def upgrade_legacy(self, segments: list) -> bool:
        """Lists from older versions do not know the first video frame (first_frame = 0, the total only counts the frames).
                It is added here: determine the number of the first frame, increase total and end by that amount (the markers
                themselves stay where they are, only a start before the first frame moves to it). Only the first packets are read."""
        changed = False
        found: dict = {}                                            # file -> first frame: every file is read once, not once per segment
        for seg in segments:
            if not seg.first_unknown:                               # saved by this version: the first frame is known, also when it is 0 (an mp4 file)
                continue
            seg.first_unknown = False                               # (the entry is written with the next save: this is not repeated at the next start)
            changed = True
            if seg.first_frame != 0 or not os.path.exists(seg.path):
                continue
            if seg.path not in found:
                try:
                    found[seg.path] = self._first_fn(seg.path, seg.fps)
                except Exception:
                    found[seg.path] = 0
            first = found[seg.path]
            if first <= 0:
                continue
            old_total = seg.total_frames
            seg.first_frame = first
            seg.total_frames = old_total + first
            seg.end = seg.total_frames if seg.end == old_total else seg.end
            seg.start = max(seg.start, first)
            seg.end = max(seg.end, seg.start + 1)
        return changed

    def refresh_list(self) -> None:
        self.lvwSegments.set_rows([segment_row(s, i) for i, s in enumerate(self.segments, 1)])
        self._bold_row = -1
        if 0 <= self.current < len(self.segments):
            self.lvwSegments.select_row(self.current)
            self.highlight()

    def Form_Unload(self):
        """Window is being closed: cancel counting and end playback cleanly before Qt tears down the video area.
                (A thread that is still running at exit would crash the program.)"""
        if self._modal_child is not None:                            # the crop window is open: cancel it
            self._modal_child.reject()
        self.save_copy_mode()                                        # (it is saved at every change too; this is for safety)
        workers = (self._counters + self._thumb_loaders + ([self._seek_worker] if self._seek_worker else [])
                   + ([self._render_worker] if self._render_worker else []))
        for worker in workers:
            worker.cancel()
        for worker in workers:
            worker.wait(5000)
        self.player.shutdown()

