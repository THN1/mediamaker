                    f"{elapsed // 3600}:{elapsed // 60 % 60:02d}:{elapsed % 60:02d}.\n\n"
                    f"The duplicate scene of {step - 1} frame(s) was cut in the middle: Marker B moved {b - i1} frame(s) back, Marker A {i2 - a} frame(s) forward.\n\n"
