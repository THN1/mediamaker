    def choose_output(self, kind: Optional[str] = None) -> Optional[str]:
        """The file dialog of Save as with the suggested name. None = cancelled. ONE dialog for all file types (mp4, mkv, avi, ts): the one in the list at the
        top is `kind` or the one chosen last in this run. The extension of the name decides the file type; without one (or with one that is no file type of the
        program, like the dot in "Dr. No") the type selected in the dialog is added.

        The dialog asks itself before an existing file is overwritten. Only if the extension had to be added here, the file the dialog saw is not the one
        that is written, so an existing file of that name is asked about (No: choose again)."""
        first = kind or self._save_type
        suggestion = batch.suggest_name(self.last_file(), first, self.multiple())
        while True:
            self._save_filter = ""
            chosen = self.ask_save_file("Save as", suggestion, containers.filters(first))
            if not chosen:
                return None
            name = chosen
            if containers.info(chosen) is None:
                name = chosen + "." + (containers.extension_of_filter(self._save_filter) or first)
            if name != chosen and os.path.exists(name):
                answer = self.ask3(f"{name} already exists.\n\nOverwrite?")
                if answer == "no":
                    suggestion = name
                    continue
                if answer == "cancel":
                    return None
            self._save_type = containers.info(name).ext
            self.remember_dir(name)                                   # offered again in the list of the Batch dialog
            return name

    def container_ok(self, output: str, copy: bool) -> bool:
        """Does the file type of the target file allow what is to be saved (containers.check)? An error is told and stops; if only something is left out (chapters
        in an avi file) it is asked whether to save anyway."""
        numbers = copymode.subtitle_numbers(self.options) if copy else []
        subtitles = []
        errors = []
        if numbers and self.segments:
            try:
                codecs = mediaprobe.subtitle_codecs(self.segments[0].path)
            except Exception:
                codecs = []
            for n in numbers:
                if n > len(codecs):
                    errors.append(f"The option subtitle names track {n}, but the file has {len(codecs)} subtitle track{'s' if len(codecs) != 1 else ''}.")
                else:
                    subtitles.append(codecs[n - 1])
        found, warnings = containers.check(output, self.chapters_valid(), subtitles, copy)
        errors += found
        if errors:
            self.msg("\n".join(errors))
            return False
        return not warnings or self.ask("\n\n".join(warnings) + "\n\nSave anyway?")

    def make_job(self, output: str) -> Job:
        return Job(output=output, profile=dict(self.profile), options=dict(self.options),
                   segments=[dataclasses.replace(s) for s in self.segments])

    def check_job(self, job: Job) -> bool:
        """Is there anything the job cannot be made of? Shows the reason and returns False."""
        if not job.segments:
            self.msg("There are no segments in the list.")
        elif not self.mnuCopyMode.isChecked() and validate_profile(job.profile):             # (copy mode ignores the profile)
            self.msg("The profile is not valid:\n" + "\n".join(validate_profile(job.profile)))
        elif missing := sorted({s.path for s in job.segments if not os.path.exists(s.path)}):
            self.msg("Source file not found: " + ", ".join(missing))
        else:
            return True
        return False

    def save_video(self, kind: Optional[str] = None) -> None:
        """Save as: the container follows from the extension of the target file, ffmpeg chooses it (see containers.py for what each one can hold)."""
        if self._render is not None:
            self.msg("A file is already being saved.")
            return
        if not self.segments:
            self.msg("There are no segments in the list.")
            return
        if self.mnuCopyMode.isChecked() and not self.copy_mode_possible():                  # said at once, before the name of the target file is asked for
            return
        output = self.choose_output(kind)
        if output is None:
            return
        job = self.make_job(output)
        if not self.check_job(job) or not self.container_ok(output, self.mnuCopyMode.isChecked()):
            return
        work = tempfile.mkdtemp(prefix="mediamaker_")
        plan = None
        try:
            if self.mnuCopyMode.isChecked():                          # copy mode: no filter, -c copy (see copymode.py)
                plan = copymode.make_plan(job.segments, job.options)
                list_path = os.path.join(work, "files.txt") if plan.kind == "concat" else None
                if list_path:
                    copymode.write_list(plan, list_path)
                chapters_file = None
                chapter_text = self.copy_chapter_text(plan, job)
                if chapter_text:
                    chapters_file = os.path.join(work, "chapters.txt")
                    with open(chapters_file, "w", encoding="utf-8", newline="\n") as f:
                        f.write(chapter_text)
                command = copymode.build_copy_command(plan, job, list_path, chapters_file=chapters_file)
                expected, total = None, plan.seconds
            else:
                write_masks(job.segments, work)                       # removelogoNN.png for the filter
                chapters_file = self.chapters_path() if self.chapters_valid() else None
                command = build_command(job, chapters_file=chapters_file)
                expected, total = expected_frames(job), total_seconds(job)
        except copymode.CopyModeError as e:
            shutil.rmtree(work, ignore_errors=True)
            self.msg(str(e))
            return
        except Exception as e:                                        # e.g. NotImplementedError for subtitles
            shutil.rmtree(work, ignore_errors=True)
            self.msg(f"The job cannot be built: {e}")
            return
        self._render = {"job": job, "output": output, "dir": work, "expected": expected, "total": total, "plan": plan, "chapters": "-map_chapters" in command}
        worker = RenderWorker(command, self._render["total"], work, self._render_fn)
        worker.progress.connect(self.render_progress)
        worker.done.connect(self.render_done)
        worker.failed.connect(self.render_failed)
        self._render_worker = worker
        for action in (self.mnuSaveMP4, self.mnuSaveAVI, self.mnuBatch):
            action.setEnabled(False)
        self.mnuCancel.setEnabled(True)
        self.bar(1, "Preparing job...")
        worker.start()

    def render_progress(self, p) -> None:
        text = f"Saving to target output file...  {p.percent:.1f} %"
        if p.eta is not None:
            text += f"   remaining {format_duration(p.eta)}"
        self.bar(p.percent, text)

    def render_finished(self) -> dict:
        """Common end of a save: menus and bar back to normal, temporary files removed. Returns the job information."""
        info, self._render, self._render_worker = self._render, None, None
        for action in (self.mnuSaveMP4, self.mnuSaveAVI, self.mnuBatch):
            action.setEnabled(True)
        self.mnuCancel.setEnabled(False)
        self.bar(0, "")
        shutil.rmtree(info["dir"], ignore_errors=True)
        return info

    def render_done(self, result) -> None:
        info = self.render_finished()
        output = info["output"]
        if result.cancelled:
            if os.path.exists(output):
                os.remove(output)                                     # an unfinished MP4 cannot be played anyway
            self.msg("Saving was cancelled; the unfinished file was deleted.")
        elif not result.ok:
            self.msg(f"ffmpeg reported an error (code {result.returncode}):\n{result.errors[-800:]}")
        else:
            try:
                ok, actual, check = verify_output(output, info["expected"]) if info["expected"] is not None else (True, 0, "")
            except Exception:
                ok, check = True, ""
            text = f"File was saved in {format_hms(result.elapsed)}."
            plan = info.get("plan")
            if plan is not None:                                      # copy mode
                text += "\n\n" + self.copy_summary(plan)
            if not ok:
                text += "\n\n" + check
            self.finish_message(text, output)                        # (no beep of our own: the window of the question makes the sound of the system, two were heard)

    def finish_message(self, text: str, output: str) -> None:
        """The message after a successful save, with the question whether to play the result now (with the program that the system has for it)."""
        if self.ask(text + "\n\nPlay now?"):
            self.play_file(output)

