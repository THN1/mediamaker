    def migrate_settings(self) -> None:
        """Old INI files: "pad" moves from the options to the profile (only if not yet set there), "focus" and the options that were tried
        for the logo mask (logo_fill, fill_sigma, mask_fill, mask_grow) are dropped.
                The file is only written if something changes."""
        changed = self.settings.migrate_legacy_keys()                 # batch, player, dialog_style: now part of options=
        changed = self.settings.migrate_tools() or changed            # [tools.linux] avidemux=, vlc=: now options (group Tools)
        raw = self.settings.options
        if "pad" in raw:
            if "pad" not in self.settings.profile:
                self.settings.update_profile({"pad": raw["pad"]})
            del raw["pad"]
            changed = True
        for key in ("focus", "logo_fill", "fill_sigma", "mask_fill", "mask_grow", "logo_rewind"):      # dropped options (see REMOVED_OPTIONS)
            if key in raw:
                del raw[key]
                changed = True
        for old, new in RENAMED_OPTIONS.items():                      # renamed options: the value moves (unless the new name is already set)
            if old in raw:
                raw.setdefault(new, raw[old])
                del raw[old]
                changed = True
        wanted = {key: DEFAULT_TOOLTIPS[key] for key in tooltip_keys() if key in DEFAULT_TOOLTIPS}
        changed = self.settings.sync_tooltips(wanted, tuple(REMOVED_OPTIONS - set(PROFILE_KEYS)) + tuple(RENAMED_OPTIONS)) or changed     # [ToolTipText]: every parameter
        if changed:
            self.settings.set_options(raw)
            self.settings.save()

