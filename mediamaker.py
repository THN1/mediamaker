    def remember_restore_backup(self, backup: bool) -> None:
        """The choice of the check box \"Save the current state as a session first\" is remembered in the option restore_backup (the other two boxes
        are not)."""
        value = "on" if backup else "off"
        if self.options.get("restore_backup", "on") != value:
            self.settings.set_option("restore_backup", value)
            self.settings.save()

    def mnuRestoreSession_Click(self):
        """Puts a saved session back: the segment list and/or the settings. The state before is saved as a session first, unless the check box in the
        window for choosing is switched off (so that the number of sessions stays manageable)."""
        infos = sessions.list_sessions(self.sessions_directory())
        if not infos:
            self.msg("There are no saved sessions yet (menu File => Backup session).")
            return
        choice = self.choose_session("Restore session", "Select the session to restore and what to restore from it:", infos, with_parts=True, with_backup=True,
                                     backup_default=self.options.get("restore_backup", "on") != "off")
        if choice is None:
            return
        (info,), parts, backup = choice
        self.remember_restore_backup(backup)
        if not info.ok:
            self.msg(f"The session {info.stamp} is damaged and cannot be restored.")
            return
        if not self.ask(f"The session {info.stamp} replaces the current " + " and ".join({"list": "segment list", "ini": "settings (INI file)", "chapters": "chapters"}[p] for p in parts)
                        + (". The current state is saved as a session first, so that you can go back." if backup else ". The current state is NOT saved first.")
                        + "\n\nRestore the session?"):
            return
        try:
            before = self.make_session(f"automatic backup before restoring {info.stamp}") if backup else None
            sessions.restore_session(info, self.settings.path, self.project_path, parts, self.chapters_path())
        except (sessions.SessionError, OSError) as e:
            self.msg(f"The session could not be restored: {e}")
            return
        self.reload_session()
        self.remember_restore_backup(backup)                         # (a restored INI file brings the value it had in the session)
        text = f"Session {info.stamp} has been restored." + (f" The state before is saved as session {before.stamp}." if before else "")
        if "list" in parts:
            self.track_choice = tracks.Choice.from_options(info.tracks)               # the choice of the multitrack dialog belongs to the list
        activated = "list" in parts and self.apply_copy_mode(info.copy_mode)       # copy mode belongs to the job, so it comes back with the list
        self.save_copy_mode()                                        # (a restored INI file has the entry it had in the session: the state of the program counts)
        if activated:
            self.copy_notice("this session", before=text)            # (one window: what was restored, and the warning)
        else:
            self.msg(text)

    def mnuDeleteSession_Click(self):
        """Deletes sessions (several can be selected)."""
        infos = sessions.list_sessions(self.sessions_directory())
        if not infos:
            self.msg("There are no saved sessions.")
            return
        choice = self.choose_session("Delete session(s)", "Select the session(s) to delete:", infos, multi=True)
        if choice is None:
            return
        chosen, _ = choice
        if not self.ask(f"Delete {len(chosen)} session{'s' if len(chosen) != 1 else ''}?"):
            return
        failed = []
        for info in chosen:
            try:
                sessions.delete_session(info)
            except OSError as e:
                failed.append(f"{info.stamp}: {e}")
        if failed:
            self.msg("Not all sessions could be deleted:\n" + "\n".join(failed))

